"""Regenerate data/ios-supplementary.txt: rare characters iPhone can display.

About 30% of the code table is CJK Extension B and later (U+20000+). The
iPhone's Chinese system font, PingFang, has glyphs for only a few hundred of
them; the rest show as a box with a question mark. The dictionary keeps only
the supplementary characters listed in this file (see tools/dictgen.py).

macOS ships the same PingFang font as iOS, so this runs on a Mac:

    pip install fonttools          # only needed for this tool
    python -m tools.fontcover

Rerun it after a major iOS/macOS update, then `python build.py`.
"""

from __future__ import annotations

import glob
import platform
import sys
from datetime import date
from pathlib import Path

from tools.cin import parse_cin
from tools.ranking import Layer, layer_of

ROOT = Path(__file__).resolve().parent.parent
CIN_PATH = ROOT / "data" / "3corner.cin"
OUT_PATH = ROOT / "data" / "ios-supplementary.txt"
FONT_GLOB = "/System/Library/AssetsV2/com_apple_MobileAsset_Font*/*.asset/AssetData/PingFang.ttc"


def read_supplementary(path: Path = OUT_PATH) -> set[str]:
    """The characters listed in data/ios-supplementary.txt."""
    chars = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            chars.add(line.split(" ", 1)[1])
    return chars


def main() -> int:
    from fontTools.ttLib import TTCollection

    fonts = sorted(glob.glob(FONT_GLOB))
    if not fonts:
        raise SystemExit(f"PingFang.ttc not found ({FONT_GLOB}); this tool runs on macOS")
    covered = set()
    for font in TTCollection(fonts[-1]).fonts:
        covered |= set(font.getBestCmap())
    chars = sorted({e.text for e in parse_cin(CIN_PATH).entries
                    if layer_of(e.text) == Layer.SUPPLEMENTARY and ord(e.text) in covered})
    header = (
        "# CJK Extension B+ characters of data/3corner.cin that iPhone can display.\n"
        "# Generated by `python -m tools.fontcover`; do not edit by hand.\n"
        f"# Font: PingFang.ttc on macOS {platform.mac_ver()[0]}, {date.today().isoformat()}\n"
    )
    OUT_PATH.write_text(header + "".join(f"U+{ord(c):X} {c}\n" for c in chars), encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}: {len(chars)} characters")
    return 0


if __name__ == "__main__":
    sys.exit(main())
